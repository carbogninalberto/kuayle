package validate

import (
	"bytes"
	"os"
	"testing"
)

func TestEgressPublicIPGuardMatchesForge(t *testing.T) {
	proxy, err := os.ReadFile("../../../devmachine/egress/public_ip.go")
	if err != nil {
		t.Fatal(err)
	}
	canonical, err := os.ReadFile("public_ip.go")
	if err != nil {
		t.Fatal(err)
	}
	want := bytes.Replace(canonical, []byte("package validate"), []byte("package main"), 1)
	want = append([]byte("// Code generated by go generate ./pkg/validate; DO NOT EDIT.\n\n"), want...)
	if !bytes.Equal(proxy, want) {
		t.Fatal("egress address guard is out of sync; run go generate ./pkg/validate from BE")
	}
}
